#!/usr/bin/env python3
"""Generate a flat image for VP8 zero-coefficient statistics parity."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/png/webp_zero_coeff_probability_checkpoint_1024x1024.png"
SIZE = (1024, 1024)
PIXEL = bytes((128, 128, 128))
EXPECTED_PIXELS_SHA256 = "b0100f136fff848063db414aa92266a7f54fc851ec01f5bc7a0ec2550e5c721f"
EXPECTED_PNG_SHA256 = "61d83f5c2e9728735afcb20e3888a236726e78dbd2b0824824b313d498f21732"


def generate_fixture() -> tuple[bytes, bytes]:
    """Return deterministic RGB pixels and their pinned PNG representation."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    pixels = PIXEL * (SIZE[0] * SIZE[1])
    pixels_sha256 = sha256(pixels).hexdigest()
    if pixels_sha256 != EXPECTED_PIXELS_SHA256:
        raise RuntimeError(
            f"generated pixel SHA-256 mismatch: expected {EXPECTED_PIXELS_SHA256}, "
            f"found {pixels_sha256}"
        )

    output = BytesIO()
    Image.frombytes("RGB", SIZE, pixels).save(
        output,
        format="PNG",
        compress_level=9,
        optimize=False,
    )
    encoded = output.getvalue()
    png_sha256 = sha256(encoded).hexdigest()
    if png_sha256 != EXPECTED_PNG_SHA256:
        raise RuntimeError(
            f"generated PNG SHA-256 mismatch: expected {EXPECTED_PNG_SHA256}, "
            f"found {png_sha256}"
        )
    return pixels, encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the fixture without rewriting it",
    )
    args = parser.parse_args()

    _, encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
