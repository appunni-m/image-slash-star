#!/usr/bin/env python3
"""Reduce a pinned YCCK H2V1 JPEG to a one-pixel SOF0 image."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/fixtures/input/images/jpeg/baseline_ycck_h2v1_single_sample_2x2.jpg"
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/baseline_ycck_h2v1_single_sample_1x1.jpg"
EXPECTED_SOURCE_SHA256 = "b7be4ab92b1acae8ad419abbbb3b9270f123af93a08fd325e176862ae0c05d74"
EXPECTED_OUTPUT_SHA256 = "6ef8f392eb8f93b3afccc85b36981cbad1c080d92c81ce99a9bce32c80f5ca40"
EXPECTED_PILLOW_CMYK_SHA256 = "fe4cfd863d3977883fd52b5794e14c8ea1cadd264db6925f83b128d1df2ce3e3"
SOF0_MARKER = b"\xff\xc0"
EOI_MARKER = b"\xff\xd9"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Change only the SOF0 dimensions from 2x2 to 1x1."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.startswith(b"\xff\xd8") or not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG no longer has its pinned SOI and EOI markers")

    sof0_offset = source.find(SOF0_MARKER)
    if sof0_offset < 0 or source.find(SOF0_MARKER, sof0_offset + len(SOF0_MARKER)) >= 0:
        raise RuntimeError("source JPEG must contain exactly one SOF0 marker")
    precision_offset = sof0_offset + 4
    height_offset = precision_offset + 1
    width_offset = height_offset + 2
    if (
        source[precision_offset] != 8
        or source[height_offset : height_offset + 2] != b"\x00\x02"
        or source[width_offset : width_offset + 2] != b"\x00\x02"
    ):
        raise RuntimeError("source JPEG SOF0 must describe an 8-bit 2x2 image")

    candidate = bytearray(source)
    candidate[height_offset + 1] = 1
    candidate[width_offset + 1] = 1
    encoded = bytes(candidate)
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow 12.2.0 accepts the YCCK image and returns pinned pixels."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        image.verify()
    with Image.open(BytesIO(encoded)) as image:
        image.load()
        if (
            image.format != "JPEG"
            or image.mode != "CMYK"
            or image.size != (1, 1)
            or image.info.get("adobe_transform") != 2
        ):
            raise RuntimeError(
                "Pillow returned an unexpected JPEG result: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}, "
                f"Adobe transform={image.info.get('adobe_transform')!r}"
            )
        pixels = image.tobytes()

    pixel_sha256 = sha256(pixels)
    if pixel_sha256 != EXPECTED_PILLOW_CMYK_SHA256:
        raise RuntimeError(
            f"Pillow CMYK SHA-256 mismatch: expected {EXPECTED_PILLOW_CMYK_SHA256}, "
            f"found {pixel_sha256}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
