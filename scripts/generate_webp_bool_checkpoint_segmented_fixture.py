#!/usr/bin/env python3
"""Generate a segmented VP8 probability parity fixture."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/png/webp_bool_checkpoint_segmented_smooth_checker_128x512.png"
)
SIZE = (128, 512)
EXPECTED_PIXELS_SHA256 = "f9ef64a18dce475566eef2d5ee52259cbd302c833ccc331b9a2989d2d000c3e7"
EXPECTED_PNG_SHA256 = "dee4e35d06dcdb2e8f82b7be8cd1bbef9e6fff60a96898b95e0f3f00fc80c487"


def generate_fixture() -> tuple[bytes, bytes]:
    """Return deterministic grayscale pixels and their pinned PNG encoding."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    pixels = bytearray(SIZE[0] * SIZE[1] * 3)
    for y in range(SIZE[1]):
        for x in range(SIZE[0]):
            value = 128 if x < SIZE[0] // 2 else (255 if (x + y) & 1 else 0)
            offset = (y * SIZE[0] + x) * 3
            pixels[offset : offset + 3] = bytes((value, value, value))

    pixels_sha256 = sha256(pixels).hexdigest()
    if pixels_sha256 != EXPECTED_PIXELS_SHA256:
        raise RuntimeError(
            f"generated pixel SHA-256 mismatch: expected {EXPECTED_PIXELS_SHA256}, "
            f"found {pixels_sha256}"
        )

    output = BytesIO()
    Image.frombytes("RGB", SIZE, bytes(pixels)).save(
        output,
        format="PNG",
        compress_level=9,
        optimize=False,
    )
    encoded = output.getvalue()
    png_sha256 = sha256(encoded).hexdigest()
    if png_sha256 != EXPECTED_PNG_SHA256:
        raise RuntimeError(
            f"generated PNG SHA-256 mismatch: expected {EXPECTED_PNG_SHA256}, "
            f"found {png_sha256}"
        )
    return bytes(pixels), encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the fixture without rewriting it",
    )
    args = parser.parse_args()

    _, encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
