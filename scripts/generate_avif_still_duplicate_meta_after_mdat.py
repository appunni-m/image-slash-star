#!/usr/bin/env python3
"""Append a duplicate still-image meta box after AVIF media data."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from PIL import Image
import yaml

from generate_decode_refs import verify_primary_oracle


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests/fixtures/input/images/avif/grid.avif"
FIXTURE = ROOT / "tests/fixtures/input/images/avif/still_duplicate_top_level_meta_after_mdat.avif"
SOURCE_SHA256 = "bae56368b348b1d847e2bfb662522599f0c63dfe62fb68826c9e42a300ff405d"
FIXTURE_SHA256 = "2279761c577c985f0c3ccfbe19a02a89f05c5fa16fb3dc1516bd5ebeb3c6702d"


def top_level_ranges(data: bytes) -> list[tuple[bytes, int, int]]:
    """Return validated top-level ISO-BMFF box ranges."""
    boxes = []
    offset = 0
    while offset < len(data):
        remaining = len(data) - offset
        if remaining < 8:
            raise RuntimeError("truncated top-level box header")

        size = int.from_bytes(data[offset : offset + 4], "big")
        kind = data[offset + 4 : offset + 8]
        header_size = 8
        if size == 1:
            if remaining < 16:
                raise RuntimeError("truncated extended-size top-level box header")
            size = int.from_bytes(data[offset + 8 : offset + 16], "big")
            header_size = 16
        elif size == 0:
            size = remaining

        if size < header_size or size > remaining:
            raise RuntimeError("invalid top-level box size")
        end = offset + size
        boxes.append((kind, offset, end))
        offset = end
    return boxes


def fixture_bytes(source: bytes) -> bytes:
    """Append the pinned primary metadata box after the complete mdat box."""
    if sha256(source).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("grid AVIF differs from its pinned source hash")

    boxes = top_level_ranges(source)
    if [kind for kind, _, _ in boxes] != [b"ftyp", b"meta", b"mdat"]:
        raise RuntimeError("grid AVIF top-level box layout changed")
    ftyp_start = boxes[0][1]
    if source[ftyp_start + 8 : ftyp_start + 12] != b"avif":
        raise RuntimeError("grid AVIF no longer uses the avif major brand")

    meta_start, meta_end = boxes[1][1:]
    candidate = source + source[meta_start:meta_end]
    candidate_boxes = top_level_ranges(candidate)
    if [kind for kind, _, _ in candidate_boxes] != [
        b"ftyp",
        b"meta",
        b"mdat",
        b"meta",
    ]:
        raise RuntimeError("duplicate meta box was not appended after mdat")
    if candidate[: len(source)] != source or candidate_boxes[-1][2] != len(candidate):
        raise RuntimeError("fixture changed source bytes or has trailing data")
    if sha256(candidate).hexdigest() != FIXTURE_SHA256:
        raise RuntimeError("generated still duplicate-meta fixture hash changed")
    return candidate


def pillow_observation(data: bytes) -> tuple[object, ...]:
    """Capture public metadata and decoded pixels through Pillow."""
    with Image.open(BytesIO(data)) as image:
        header = (image.format, image.mode, image.size, image.n_frames, dict(image.info))
    with Image.open(BytesIO(data)) as image:
        image.verify()
    with Image.open(BytesIO(data)) as image:
        image.load()
        pixels = image.tobytes()
    return (*header, pixels)


def generate(check: bool = False) -> None:
    """Verify Pillow parity and write or check the deterministic fixture."""
    manifest = yaml.safe_load((ROOT / "manifest.yaml").read_text(encoding="utf-8"))
    verify_primary_oracle(manifest)

    source = SOURCE.read_bytes()
    candidate = fixture_bytes(source)
    if pillow_observation(candidate) != pillow_observation(source):
        raise RuntimeError("Pillow observation changed after appending duplicate meta")

    if check:
        if not FIXTURE.is_file() or FIXTURE.read_bytes() != candidate:
            raise RuntimeError(f"fixture is missing or differs from generated bytes: {FIXTURE}")
    elif FIXTURE.exists():
        if FIXTURE.read_bytes() != candidate:
            raise RuntimeError(f"refusing to replace a different fixture at {FIXTURE}")
    else:
        FIXTURE.write_bytes(candidate)
    print(
        f"Verified {FIXTURE} ({len(candidate)} bytes, sha256={FIXTURE_SHA256})"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    generate(check=arguments.check)


if __name__ == "__main__":
    main()
