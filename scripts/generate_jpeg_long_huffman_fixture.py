#!/usr/bin/env python3
"""Generate a grayscale JPEG that uses valid eleven-bit Huffman codes."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/long_huffman_code_slow_path.jpg"
EXPECTED_SHA256 = "312fba08b51786bd7e40a2d84657af9d358e888a66d0d13423d8b6e79ce57637"


def segment(marker: int, payload: bytes) -> bytes:
    """Return one length-delimited JPEG marker segment."""
    length = len(payload) + 2
    if length > 0xFFFF:
        raise ValueError("JPEG marker payload exceeds the 16-bit segment limit")
    return b"\xff" + bytes((marker,)) + length.to_bytes(2, "big") + payload


def generate_fixture() -> bytes:
    """Build a one-block SOF0 stream whose zero codes are eleven bits long."""
    quantization = segment(0xDB, bytes((0,)) + bytes((1,)) * 64)
    frame = segment(
        0xC0,
        bytes((8, 0, 8, 0, 8, 1, 1, 0x11, 0)),
    )

    # Each table has exactly one zero-valued symbol at length eleven. Its
    # canonical code is eleven zero bits, which exceeds JPEG's ten-bit lookup.
    counts = bytes((0,) * 10 + (1,) + (0,) * 5)
    dc_table = bytes((0,)) + counts + bytes((0,))
    ac_table = bytes((0x10,)) + counts + bytes((0,))
    huffman_tables = segment(0xC4, dc_table + ac_table)

    scan = segment(0xDA, bytes((1, 1, 0, 0, 63, 0)))
    # DC category 0 and AC EOB are 22 zero bits; JPEG pads the last byte with
    # two one bits, yielding 00 00 03.
    entropy = bytes((0x00, 0x00, 0x03))
    encoded = b"\xff\xd8" + quantization + frame + huffman_tables + scan + entropy + b"\xff\xd9"
    actual = hashlib.sha256(encoded).hexdigest()
    if actual != EXPECTED_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_SHA256}, found {actual}"
        )
    return encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
