#!/usr/bin/env python3
"""Generate grayscale JPEGs for long Huffman lookup and continuation paths."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/long_huffman_code_slow_path.jpg"
EXPECTED_SHA256 = "312fba08b51786bd7e40a2d84657af9d358e888a66d0d13423d8b6e79ce57637"
CONTINUATION_OUTPUT = (
    ROOT / "tests/fixtures/input/images/jpeg/long_huffman_code_continuation.jpg"
)
CONTINUATION_SHA256 = "32e5fe3ccf7e9d5d2f0580be8bc0e5801dc5e6535d1e71d71df1fa02a5a19213"


def segment(marker: int, payload: bytes) -> bytes:
    """Return one length-delimited JPEG marker segment."""
    length = len(payload) + 2
    if length > 0xFFFF:
        raise ValueError("JPEG marker payload exceeds the 16-bit segment limit")
    return b"\xff" + bytes((marker,)) + length.to_bytes(2, "big") + payload


def generate_fixture_with_code_length(code_length: int) -> bytes:
    """Build a one-block SOF0 stream with one zero code at ``code_length``."""
    if code_length not in (11, 12):
        raise ValueError(
            "the long-Huffman fixtures support eleven- and twelve-bit codes"
        )

    quantization = segment(0xDB, bytes((0,)) + bytes((1,)) * 64)
    frame = segment(
        0xC0,
        bytes((8, 0, 8, 0, 8, 1, 1, 0x11, 0)),
    )

    # Each table has one zero-valued symbol. Its canonical code is all zeroes
    # and exceeds JPEG's ten-bit lookup; twelve bits also force continuation
    # after the fast decoder's initial eleven-bit read.
    counts = bytearray(16)
    counts[code_length - 1] = 1
    counts = bytes(counts)
    dc_table = bytes((0,)) + counts + bytes((0,))
    ac_table = bytes((0x10,)) + counts + bytes((0,))
    huffman_tables = segment(0xC4, dc_table + ac_table)

    scan = segment(0xDA, bytes((1, 1, 0, 0, 63, 0)))
    # DC category 0 and AC EOB each use the selected-length all-zero code.
    # JPEG pads a partial final byte with one bits.
    entropy_bits = 2 * code_length
    padding_bits = (-entropy_bits) % 8
    entropy = ((1 << padding_bits) - 1).to_bytes(
        (entropy_bits + padding_bits) // 8,
        "big",
    )
    return (
        b"\xff\xd8"
        + quantization
        + frame
        + huffman_tables
        + scan
        + entropy
        + b"\xff\xd9"
    )


def generate_fixture() -> bytes:
    """Build the existing eleven-bit lookup-fallback fixture."""
    encoded = generate_fixture_with_code_length(11)
    actual = hashlib.sha256(encoded).hexdigest()
    if actual != EXPECTED_SHA256:
        raise RuntimeError(
            "generated JPEG SHA-256 mismatch: "
            f"expected {EXPECTED_SHA256}, found {actual}"
        )
    return encoded


def generate_continuation_fixture() -> bytes:
    """Build a twelve-bit code that continues past the initial slow-path read."""
    encoded = generate_fixture_with_code_length(12)
    actual = hashlib.sha256(encoded).hexdigest()
    if actual != CONTINUATION_SHA256:
        raise RuntimeError(
            "generated JPEG SHA-256 mismatch: "
            f"expected {CONTINUATION_SHA256}, found {actual}"
        )
    return encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    fixtures = (
        (OUTPUT, generate_fixture()),
        (CONTINUATION_OUTPUT, generate_continuation_fixture()),
    )
    if args.check:
        for path, encoded in fixtures:
            if not path.is_file() or path.read_bytes() != encoded:
                raise RuntimeError(
                    f"{path.relative_to(ROOT)} differs from generated bytes"
                )
            print(f"Fixture matches: {path.relative_to(ROOT)}")
        return 0

    for path, encoded in fixtures:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(encoded)
        print(f"Wrote {path.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
