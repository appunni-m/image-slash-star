#!/usr/bin/env python3
"""Add an oversized post-scan COM segment to a progressive JPEG."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/fixtures/input/images/jpeg/progressive.jpg"
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/progressive_trailing_com_oversized.jpg"
EXPECTED_SOURCE_SHA256 = "ee474cd556c6bfc7e937dfba671e204ef166eec162eddb3a360f70f574260a3d"
EXPECTED_OUTPUT_SHA256 = "c18a2f350fa0905e4967b085d5ba74960dda23d684048c1a85ae81da819a759d"
TRAILING_COM_AND_EOI = bytes.fromhex("fffe0014") + b"abcdefgh\xff\xd9"
EOI_MARKER = b"\xff\xd9"
EXPECTED_PILLOW_ERROR = "image file is truncated (0 bytes not processed)"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Replace the progressive source EOI with a short oversized COM segment."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.startswith(b"\xff\xd8") or not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG no longer has its pinned SOI and EOI markers")
    if b"\xff\xc2" not in source:
        raise RuntimeError("source JPEG no longer contains a progressive SOF2 marker")

    encoded = source[:-len(EOI_MARKER)] + TRAILING_COM_AND_EOI
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Pin Pillow's open/verify behavior and the expected decode failure."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (128, 128):
            raise RuntimeError(
                "Pillow returned an unexpected progressive JPEG: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        image.verify()

    with Image.open(BytesIO(encoded)) as image:
        try:
            image.load()
        except OSError as error:
            if type(error) is not OSError or str(error) != EXPECTED_PILLOW_ERROR:
                raise RuntimeError(
                    "Pillow's truncated-COM error changed: "
                    f"{type(error).__name__}: {error}"
                ) from error
        else:
            raise RuntimeError("Pillow unexpectedly decoded the oversized COM fixture")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
