#!/usr/bin/env python3
"""Generate malformed trailing-DHT JPEG inputs for decoder parity."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INPUT_DIR = ROOT / "tests/fixtures/input/images/jpeg"
SOURCE = INPUT_DIR / "baseline_444_single_scan_trailing_com.jpg"
SOURCE_SHA256 = "cf8e4443dcff4df7858b6573664aa3fe73dd401827aa293d0eca84eb0667f666"
TRAILING_COMMENT = bytes.fromhex("fffe00046f6bffd9")
BROKEN_DATA_MESSAGE = "broken data stream when reading image file"
MALFORMED_DHT = {
    "baseline_444_single_scan_trailing_dht_length_one.jpg": (
        bytes.fromhex("ffc40001"),
        "ce200aef72bb9a259f48cf9f154a51ca8ba16280601b39c7076c8c4c6df07b0a",
    ),
    "baseline_444_single_scan_trailing_dht_truncated_counts.jpg": (
        bytes.fromhex("ffc4000300"),
        "eb9cc39fb74763240136310a0fed1af15cc133377f83257772ae204c57f3a028",
    ),
    "baseline_444_single_scan_trailing_dht_truncated_values.jpg": (
        bytes.fromhex("ffc400130001") + bytes(15),
        "3615cb0eea96e135169f3d944b0596a982de6e019bb3a4e9377c70aa1667d146",
    ),
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixtures() -> dict[Path, bytes]:
    """Replace an anchored trailing COM with bounded malformed DHT segments."""
    source = SOURCE.read_bytes()
    source_sha = sha256(source)
    if source_sha != SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {SOURCE_SHA256}, found {source_sha}"
        )
    if not source.endswith(TRAILING_COMMENT):
        raise RuntimeError("source JPEG no longer ends in its pinned trailing COM and EOI")

    prefix = source[: -len(TRAILING_COMMENT)]
    fixtures = {}
    for filename, (dht, expected_sha) in MALFORMED_DHT.items():
        encoded = prefix + dht + b"\xff\xd9"
        actual_sha = sha256(encoded)
        if actual_sha != expected_sha:
            raise RuntimeError(
                f"{filename} SHA-256 mismatch: expected {expected_sha}, found {actual_sha}"
            )
        fixtures[INPUT_DIR / filename] = encoded
    return fixtures


def verify_pillow_references(fixtures: dict[Path, bytes]) -> None:
    """Pin structural verification and decode failure to Pillow 12.2.0."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    for path, encoded in fixtures.items():
        with Image.open(BytesIO(encoded)) as image:
            image.verify()

        try:
            with Image.open(BytesIO(encoded)) as image:
                image.load()
        except OSError as error:
            if str(error) != BROKEN_DATA_MESSAGE:
                raise RuntimeError(f"unexpected Pillow error for {path.name}: {error}") from error
        else:
            raise RuntimeError(f"Pillow unexpectedly decoded {path.name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify committed fixtures without requiring Pillow or rewriting them",
    )
    args = parser.parse_args()

    fixtures = generate_fixtures()
    if args.check:
        for path, encoded in fixtures.items():
            if not path.is_file() or path.read_bytes() != encoded:
                raise RuntimeError(f"{path.relative_to(ROOT)} differs from generated bytes")
        print(f"Verified {len(fixtures)} malformed trailing-DHT JPEG fixtures")
        return 0

    verify_pillow_references(fixtures)
    for path, encoded in fixtures.items():
        path.write_bytes(encoded)
        print(f"Wrote {path.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
