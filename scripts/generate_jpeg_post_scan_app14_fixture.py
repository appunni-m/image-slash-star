#!/usr/bin/env python3
"""Insert a conflicting Adobe APP14 segment after a YCCK JPEG scan."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/fixtures/input/images/jpeg/baseline_ycck_subsampled_17x9.jpg"
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/post_scan_conflicting_adobe_app14.jpg"
EXPECTED_SOURCE_SHA256 = "39d712b61d2abe430c9767a1630a4f76dd8757d2b1357cec8524af4f414c23b7"
EXPECTED_OUTPUT_SHA256 = "8e64e01abd202d4a5196ab021f44f0f7b45d22f650a2ed871a698b5a4a2e0520"
EXPECTED_PILLOW_CMYK_SHA256 = "c3d39cb993e20e4062c928e8fdad94ada64377bd4095e7203194a2e5efc48f05"
APP14_SEGMENT = bytes.fromhex("ffee000e41646f626500640000000000")
EOI_MARKER = b"\xff\xd9"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Insert one APP14 segment immediately before the source EOI marker."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG no longer ends with EOI")

    encoded = source[:-len(EOI_MARKER)] + APP14_SEGMENT + EOI_MARKER
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow accepts the conflict and preserves its pre-scan transform."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        image.verify()
    with Image.open(BytesIO(encoded)) as image:
        image.load()
        if (
            image.format != "JPEG"
            or image.mode != "CMYK"
            or image.size != (17, 9)
            or image.info.get("adobe_transform") != 2
        ):
            raise RuntimeError(
                "Pillow returned an unexpected YCCK JPEG result: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}, "
                f"adobe_transform={image.info.get('adobe_transform')!r}"
            )
        pixels = image.tobytes()

    pixel_sha256 = sha256(pixels)
    if pixel_sha256 != EXPECTED_PILLOW_CMYK_SHA256:
        raise RuntimeError(
            f"Pillow CMYK SHA-256 mismatch: expected {EXPECTED_PILLOW_CMYK_SHA256}, "
            f"found {pixel_sha256}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
