#!/usr/bin/env python3
"""Write and validate the 16-bit grayscale partial-frame APNG fixture."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/png/apng_gray16_partial_frame.png"
EXPECTED_SHA256 = "ed7171393de78d2373745669ce8ed3b8cb715c6cadcfdae66f42467d25e33c4f"
EXPECTED_FRAME_SHA256 = (
    "2196d24a989fee982488070afd64307bbcc2b64ff5c7aecffc3850657e9eefe0",
    "5d985624217caa89becf86421e648670b52352f63fd672080e070faa89195725",
)
FIXTURE_HEX = (
    "89504e470d0a1a0a0000000d494844520000000200000001100000000081d9fc15"
    "000000086163544c0000000200000000f38d93700000001a6663544c00000000"
    "000000020000000100000000000000000001000a0000f929b6790000000d494441"
    "54789c631032597d1600030c01bf6eb9c65d0000001a6663544c000000010000"
    "00010000000100000001000000000001000a0000008205c40000000f6664415400"
    "000002789c63f8ff1f00030001ff7a8411ce0000000049454e44ae426082"
)


def generate_fixture() -> bytes:
    data = bytes.fromhex(FIXTURE_HEX)
    if sha256(data).hexdigest() != EXPECTED_SHA256:
        raise RuntimeError("generated APNG SHA-256 differs from its pinned fixture")
    return data


def verify_pillow_reference(data: bytes) -> None:
    """Assert exact Pillow verification, sequence metadata, and frame samples."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")
    with Image.open(BytesIO(data)) as image:
        image.verify()

    with Image.open(BytesIO(data)) as image:
        if image.format != "PNG" or image.mode != "I;16" or image.size != (2, 1):
            raise RuntimeError("Pillow returned an unexpected 16-bit grayscale APNG")
        if image.n_frames != 2 or not image.is_animated:
            raise RuntimeError("Pillow did not expose the expected two-frame animation")
        for index, expected_sha256 in enumerate(EXPECTED_FRAME_SHA256):
            image.seek(index)
            image.load()
            frame = image.tobytes()
            if len(frame) != 4 or sha256(frame).hexdigest() != expected_sha256:
                raise RuntimeError(f"Pillow APNG frame {index} differs from its exact reference")
            if image.info.get("duration") != 100:
                raise RuntimeError(f"Pillow APNG frame {index} has an unexpected duration")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()
    data = generate_fixture()

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != data:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(data)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(data)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
