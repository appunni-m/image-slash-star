#!/usr/bin/env python3
"""Generate larger seeded RGB noise for VP8 checkpoint carry-run parity."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from random import Random


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/png/webp_bool_checkpoint_noise_128x192.png"
SIZE = (128, 192)
SEED = 0x5A17E
EXPECTED_PIXELS_SHA256 = "2a9b69cb57455c73c1e66be5f68a3590f4f18bcdd60e517ddbd5c6997785371f"
EXPECTED_PNG_SHA256 = "3f8a6f9ff2cb3e89124c7b03836df50426d7d17e78976ee32cb8200cd5273962"


def generate_fixture() -> tuple[bytes, bytes]:
    """Return deterministic RGB pixels and their pinned PNG representation."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    pixels = Random(SEED).randbytes(SIZE[0] * SIZE[1] * 3)
    pixels_sha256 = sha256(pixels).hexdigest()
    if pixels_sha256 != EXPECTED_PIXELS_SHA256:
        raise RuntimeError(
            f"generated pixel SHA-256 mismatch: expected {EXPECTED_PIXELS_SHA256}, "
            f"found {pixels_sha256}"
        )

    output = BytesIO()
    Image.frombytes("RGB", SIZE, pixels).save(
        output,
        format="PNG",
        compress_level=9,
        optimize=False,
    )
    encoded = output.getvalue()
    png_sha256 = sha256(encoded).hexdigest()
    if png_sha256 != EXPECTED_PNG_SHA256:
        raise RuntimeError(
            f"generated PNG SHA-256 mismatch: expected {EXPECTED_PNG_SHA256}, "
            f"found {png_sha256}"
        )
    return pixels, encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    _, encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
