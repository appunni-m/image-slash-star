#!/usr/bin/env python3
"""Tile the pinned RGB noise image for lossless WebP match-cost parity."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/png"
    / "webp_lossless_cost_manager_tiled_noise_128x1024.png"
)
SIZE = (128, 1024)
TILE_COUNT = 8
EXPECTED_PIXELS_SHA256 = "30c9b27c4c3fd7f2d7371019bce0ff38b1583de3540508102d594db55c9e09b7"
EXPECTED_PNG_SHA256 = "d5bd376e0d5badf64d0e47ca1e7c41422ad8f7d59bc6f4af72ce526557a7c67e"


def generate_png() -> bytes:
    """Return eight exact vertical repeats of the pinned 128×128 RGB noise tile."""
    from generate_webp_bool_carry_noise_fixture import generate_fixture

    base_pixels, _ = generate_fixture()
    pixels = base_pixels * TILE_COUNT
    pixels_sha256 = sha256(pixels).hexdigest()
    if pixels_sha256 != EXPECTED_PIXELS_SHA256:
        raise RuntimeError(
            f"generated pixel SHA-256 mismatch: expected {EXPECTED_PIXELS_SHA256}, "
            f"found {pixels_sha256}"
        )

    output = BytesIO()
    Image.frombytes("RGB", SIZE, pixels).save(
        output,
        format="PNG",
        compress_level=9,
        optimize=False,
    )
    encoded = output.getvalue()
    png_sha256 = sha256(encoded).hexdigest()
    if png_sha256 != EXPECTED_PNG_SHA256:
        raise RuntimeError(
            f"generated PNG SHA-256 mismatch: expected {EXPECTED_PNG_SHA256}, "
            f"found {png_sha256}"
        )
    return encoded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_png()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(
                f"{OUTPUT.relative_to(ROOT)} differs from generated bytes"
            )
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
