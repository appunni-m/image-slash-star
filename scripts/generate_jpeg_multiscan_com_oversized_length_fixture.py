#!/usr/bin/env python3
"""Add a truncated trailing COM payload to a multi-scan baseline JPEG."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_444_multiscan_interleaved_restart.jpg"
)
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_444_multiscan_com_oversized_length.jpg"
)
EXPECTED_SOURCE_SHA256 = "ddbcf29eb1549aae0356661ff2b879b7b2b23b7aae924adbb424af22246e20d7"
EXPECTED_OUTPUT_SHA256 = "4177af354fc11b8ff4ecd71f7e75e37afb9528806c18e524927946e4b004853c"
EXPECTED_PILLOW_ERROR = "image file is truncated (0 bytes not processed)"
EOI_MARKER = b"\xff\xd9"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Replace terminal EOI with COM declaring a truncated 65,533-byte body."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if source.count(b"\xff\xda") < 2 or not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG is no longer the pinned multi-scan baseline image")

    encoded = source[:-len(EOI_MARKER)] + bytes.fromhex("fffeffffffd9")
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow 12.2.0 accepts the header and rejects truncated pixels."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (16, 8):
            raise RuntimeError(
                "Pillow returned an unexpected JPEG header: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        try:
            image.load()
        except OSError as error:
            if str(error) != EXPECTED_PILLOW_ERROR:
                raise RuntimeError(
                    f"Pillow truncation error changed: expected {EXPECTED_PILLOW_ERROR!r}, "
                    f"found {str(error)!r}"
                ) from error
        else:
            raise RuntimeError("Pillow unexpectedly decoded the truncated COM payload")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
