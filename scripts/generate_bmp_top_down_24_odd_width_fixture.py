#!/usr/bin/env python3
"""Generate the top-down odd-width 24-bit BMP parity fixture."""

from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path
import struct
import tempfile

from PIL import Image, __version__ as PILLOW_VERSION

from generate_test_assets import write_bmp_24

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/input/images/bmp/top_down_24_odd_width.bmp"
EXPECTED_FILE_SHA256 = "e33cd8541c6e05f96d02f256fdc94baa80d072ec4146f08129ef9f87053d0b19"
EXPECTED_PIXELS_SHA256 = "3ea707e3df8c76a38c8c72d2c3e263806f92aef645741ed183127b35ce04f925"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def expected_pixels() -> bytes:
    return bytes(
        channel
        for y in range(5)
        for x in range(9)
        for channel in (
            (23 * x + 17 * y) & 0xFF,
            (29 * x + 41 * y) & 0xFF,
            (37 * x + 53 * y) & 0xFF,
        )
    )


def generate_fixture() -> bytes:
    image = Image.new("RGB", (9, 5))
    image.putdata(
        [
            (
                (23 * x + 17 * y) & 0xFF,
                (29 * x + 41 * y) & 0xFF,
                (37 * x + 53 * y) & 0xFF,
            )
            for y in range(5)
            for x in range(9)
        ]
    )
    with tempfile.TemporaryDirectory(prefix="bmp-top-down-odd-width-") as directory:
        path = Path(directory) / OUTPUT.name
        write_bmp_24(path, image, top_down=True)
        encoded = path.read_bytes()

    if sha256(encoded) != EXPECTED_FILE_SHA256:
        raise RuntimeError("generated BMP SHA-256 differs from its pinned fixture")
    if len(encoded) != 194:
        raise RuntimeError(f"generated BMP has an unexpected length: {len(encoded)}")
    dib_size, width, height = struct.unpack_from("<Iii", encoded, 14)
    planes, depth = struct.unpack_from("<HH", encoded, 26)
    compression, raster_size = struct.unpack_from("<II", encoded, 30)
    if (dib_size, width, height, planes, depth, compression, raster_size) != (
        40,
        9,
        -5,
        1,
        24,
        0,
        140,
    ):
        raise RuntimeError("generated BMP does not have the expected top-down INFO layout")
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow's full-file decode and exact RGB samples."""
    if PILLOW_VERSION != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PILLOW_VERSION}")

    with Image.open(io.BytesIO(encoded)) as image:
        image.verify()
    with Image.open(io.BytesIO(encoded)) as image:
        image.load()
        pixels = image.tobytes()
        if image.format != "BMP" or image.mode != "RGB" or image.size != (9, 5):
            raise RuntimeError("Pillow returned an unexpected BMP format, mode, or size")
        if pixels != expected_pixels() or sha256(pixels) != EXPECTED_PIXELS_SHA256:
            raise RuntimeError("Pillow decoded pixels differ from the pinned reference")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()
    encoded = generate_fixture()

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print("BMP top-down odd-width fixture matches its pinned full-file bytes")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
