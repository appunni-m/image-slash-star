#!/usr/bin/env python3
"""Generate a complete baseline grayscale JPEG with a repeated component scan."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from generate_test_assets import jpeg_scan_segments


ROOT = Path(__file__).resolve().parents[1]
INPUT_DIR = ROOT / "tests/fixtures/input/images/jpeg"
SOURCE_NAME = "grayscale_sampling_420_128x128.jpg"
SOURCE_SHA256 = "ec3d968f651020392282ddf1ff6734ae45d95ccd4f4f7e69658f8a25be435cce"
OUTPUT_NAME = "baseline_grayscale_duplicate_component_scan.jpg"
OUTPUT_SHA256 = "73bd46f8c218d547ba1341a2750d33f178dcf85be326e7d6ad28d166f01721a5"
PILLOW_ERROR = "broken data stream when reading image file"


def generate_fixture() -> bytes:
    """Duplicate the pinned sole baseline scan without changing its entropy."""
    source = (INPUT_DIR / SOURCE_NAME).read_bytes()
    source_hash = sha256(source).hexdigest()
    if source_hash != SOURCE_SHA256:
        raise RuntimeError(f"pinned grayscale source changed: {source_hash}")

    scans, eoi = jpeg_scan_segments(source)
    if len(scans) != 1 or eoi != len(source) - 2 or not source.endswith(b"\xff\xd9"):
        raise RuntimeError("pinned grayscale source must have one scan ending at EOI")
    scan_start, entropy_end, spectral_start, spectral_end, approximation, _ = scans[0]
    if (spectral_start, spectral_end, approximation) != (0, 63, 0) or entropy_end != eoi:
        raise RuntimeError("pinned grayscale source is not one complete baseline scan")
    sos_length = int.from_bytes(source[scan_start + 2 : scan_start + 4], "big")
    if sos_length != 8 or source[scan_start + 4] != 1:
        raise RuntimeError("pinned grayscale source must have a one-component SOS")

    duplicate = source[:eoi] + source[scan_start:entropy_end] + source[eoi:]
    duplicate_hash = sha256(duplicate).hexdigest()
    if duplicate_hash != OUTPUT_SHA256:
        raise RuntimeError(f"generated grayscale scan fixture hash changed: {duplicate_hash}")
    return duplicate


def verify_pillow_reference(data: bytes) -> None:
    """Pin Pillow's structural acceptance and decode error for this input."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")
    with Image.open(BytesIO(data)) as image:
        image.verify()

    try:
        with Image.open(BytesIO(data)) as image:
            image.load()
    except OSError as error:
        if str(error) != PILLOW_ERROR:
            raise RuntimeError(f"unexpected Pillow decode error: {error}") from error
    else:
        raise RuntimeError("Pillow unexpectedly decoded the duplicate grayscale scan")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed fixture")
    args = parser.parse_args()

    data = generate_fixture()
    path = INPUT_DIR / OUTPUT_NAME
    if args.check:
        if not path.is_file() or path.read_bytes() != data:
            raise RuntimeError(f"{path.relative_to(ROOT)} differs from generated bytes")
        print(f"Verified {path.relative_to(ROOT)} ({len(data)} bytes)")
        return 0

    verify_pillow_reference(data)
    if path.exists() and path.read_bytes() != data:
        raise RuntimeError(f"refusing to replace a different existing fixture: {path}")
    path.write_bytes(data)
    print(f"Wrote {path.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
