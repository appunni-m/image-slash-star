#!/usr/bin/env python3
"""Remove JPEG EOI and leave a marker-fill run ending at EOF."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/fixtures/input/images/jpeg/baseline.jpg"
OUTPUT = ROOT / "tests/fixtures/input/images/jpeg/missing_eoi_marker_fill_eof.jpg"
EXPECTED_SOURCE_SHA256 = "c669c42fcf388430afd4400bbdcbc66f30165d50e4b162ed77e1f67392cce4ef"
EXPECTED_OUTPUT_SHA256 = "ad5398e03bd8243582d0f93d4c14cbd2e812afa398e41db5b9a7455736cd10bf"
EOI_MARKER = b"\xff\xd9"
MARKER_FILL_EOF = b"\xff\xff"
EXPECTED_PILLOW_ERROR = "image file is truncated (53 bytes not processed)"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Replace the terminal EOI marker with two marker-prefix bytes."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG no longer ends with the pinned EOI marker")

    encoded = source[:-len(EOI_MARKER)] + MARKER_FILL_EOF
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Pin Pillow's successful verify and observable truncated-load error."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (128, 128):
            raise RuntimeError(
                "Pillow returned unexpected JPEG metadata: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        image.verify()

    try:
        with Image.open(BytesIO(encoded)) as image:
            image.load()
    except OSError as error:
        if str(error) != EXPECTED_PILLOW_ERROR:
            raise RuntimeError(f"Pillow truncation error changed: {error}") from error
    else:
        raise RuntimeError("Pillow unexpectedly decoded the JPEG without an EOI marker")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
