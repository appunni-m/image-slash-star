#!/usr/bin/env python3
"""Generate complete-scan JPEGs ending with incomplete trailing DHT lengths."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INPUT_DIR = ROOT / "tests/fixtures/input/images/jpeg"
SOURCE = INPUT_DIR / "baseline_444_single_scan_trailing_com.jpg"
OUTPUT = INPUT_DIR / "baseline_444_single_scan_dht_missing_length.jpg"
PARTIAL_LENGTH_OUTPUT = INPUT_DIR / "baseline_444_single_scan_dht_partial_length.jpg"
EXPECTED_SOURCE_SHA256 = "cf8e4443dcff4df7858b6573664aa3fe73dd401827aa293d0eca84eb0667f666"
EXPECTED_OUTPUT_SHA256 = "7c8f8b67f671325d938bb236da0d4d702b89f636128ae3328dfa494b669b345d"
EXPECTED_PARTIAL_LENGTH_SHA256 = "bee79bee58292421431950ef3ee8f0b3b09d93a8a3d0e990e1eab76abb6015be"
EXPECTED_PILLOW_RGB_SHA256 = "7382706a9ecb0f6acae26e7c1c9a9be0e9471233c1a0c0da48d08a458115be2f"
TRAILING_COMMENT = bytes.fromhex("fffe00046f6bffd9")
TRAILING_DHT_MARKER = bytes.fromhex("ffc4")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Replace the pinned trailing COM and EOI with a bare DHT marker."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.endswith(TRAILING_COMMENT):
        raise RuntimeError("source JPEG no longer ends in its pinned trailing COM and EOI")

    encoded = source[: -len(TRAILING_COMMENT)] + TRAILING_DHT_MARKER
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def generate_partial_length_fixture() -> bytes:
    """Append one incomplete DHT length byte after the pinned bare marker."""
    encoded = generate_fixture() + b"\x00"
    output_sha256 = sha256(encoded)
    if output_sha256 != EXPECTED_PARTIAL_LENGTH_SHA256:
        raise RuntimeError(
            f"partial-length JPEG SHA-256 mismatch: expected "
            f"{EXPECTED_PARTIAL_LENGTH_SHA256}, found {output_sha256}"
        )
    return encoded


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow verifies and decodes the finished scan despite its tail."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        image.verify()
    with Image.open(BytesIO(encoded)) as image:
        image.load()
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (8, 8):
            raise RuntimeError(
                "Pillow returned an unexpected JPEG result: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        pixels = image.tobytes()

    pixel_sha256 = sha256(pixels)
    if pixel_sha256 != EXPECTED_PILLOW_RGB_SHA256:
        raise RuntimeError(
            f"Pillow RGB SHA-256 mismatch: expected {EXPECTED_PILLOW_RGB_SHA256}, "
            f"found {pixel_sha256}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    fixtures = {
        OUTPUT: generate_fixture(),
        PARTIAL_LENGTH_OUTPUT: generate_partial_length_fixture(),
    }
    if args.check:
        for path, encoded in fixtures.items():
            if not path.is_file() or path.read_bytes() != encoded:
                raise RuntimeError(f"{path.relative_to(ROOT)} differs from generated bytes")
        print(f"Verified {len(fixtures)} trailing-DHT fixtures")
        return 0

    for path, encoded in fixtures.items():
        verify_pillow_reference(encoded)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(encoded)
        print(f"Wrote {path.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
