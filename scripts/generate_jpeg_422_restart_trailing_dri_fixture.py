#!/usr/bin/env python3
"""Add a post-scan DRI change to a restart-coded baseline 4:2:2 JPEG."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_422_restart_blocks_1.jpg"
)
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_422_restart_trailing_dri_zero.jpg"
)
EXPECTED_SOURCE_SHA256 = "5b028c8f6b91661cbed9019bed9012de5972a48c7a33c6ebf09488b6fd1c2126"
EXPECTED_OUTPUT_SHA256 = "fb5c738ab0b6dfc013cae23a72f5672d346693d58a8f2f1b610729f2cce65ecc"
EXPECTED_PILLOW_RGB_SHA256 = "b1e9a9f445e2c91f72818b9a24c1668e212042364c9f7f61d244b9cb63ce25aa"
TRAILING_DRI_ZERO = bytes.fromhex("ffdd00040000")
EOI_MARKER = b"\xff\xd9"


def generate_fixture() -> bytes:
    """Insert DRI=0 before EOI without changing the preceding scan."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source).hexdigest()
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )
    if not source.endswith(EOI_MARKER):
        raise RuntimeError("source JPEG no longer ends with EOI")

    encoded = source[: -len(EOI_MARKER)] + TRAILING_DRI_ZERO + EOI_MARKER
    output_sha256 = sha256(encoded).hexdigest()
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return encoded


def pillow_rgb(data: bytes, label: str) -> bytes:
    """Verify one JPEG with the pinned Pillow oracle and return its RGB bytes."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(data)) as image:
        image.verify()
    with Image.open(BytesIO(data)) as image:
        image.load()
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (128, 128):
            raise RuntimeError(
                f"Pillow returned unexpected {label} metadata: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        return image.tobytes()


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm Pillow accepts the candidate and the trailing DRI leaves pixels unchanged."""
    pixels = pillow_rgb(encoded, "candidate")
    pixel_sha256 = sha256(pixels).hexdigest()
    if pixel_sha256 != EXPECTED_PILLOW_RGB_SHA256:
        raise RuntimeError(
            f"Pillow RGB SHA-256 mismatch: expected {EXPECTED_PILLOW_RGB_SHA256}, "
            f"found {pixel_sha256}"
        )

    source_pixels = pillow_rgb(SOURCE.read_bytes(), "source")
    if pixels != source_pixels:
        raise RuntimeError("trailing DRI changed Pillow's decoded JPEG pixels")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
