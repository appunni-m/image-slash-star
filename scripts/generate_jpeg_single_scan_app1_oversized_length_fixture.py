#!/usr/bin/env python3
"""Change a post-scan baseline JPEG COM marker to APP1 with an oversized length."""

from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_444_single_scan_com_oversized_length.jpg"
)
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_444_single_scan_app1_oversized_length.jpg"
)
EXPECTED_SOURCE_SHA256 = "b554f0b32009da0282d524952288a3dd561c85f7d50591af6a3a997ba13c15f0"
EXPECTED_OUTPUT_SHA256 = "53a5354d026c35b5a1f105af5192e1213fb873bae48b253728a85fcbc07add4f"
EXPECTED_PILLOW_RGB_SHA256 = "7382706a9ecb0f6acae26e7c1c9a9be0e9471233c1a0c0da48d08a458115be2f"
SOS_MARKER = b"\xff\xda"
COM_MARKER = b"\xff\xfe"
APP1_MARKER = b"\xff\xe1"
EOI_MARKER = b"\xff\xd9"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate_fixture() -> bytes:
    """Replace the post-scan COM marker while preserving its oversized length."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source)
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )

    scan_start = source.find(SOS_MARKER)
    eoi_start = source.rfind(EOI_MARKER)
    comment_start = source.rfind(COM_MARKER, scan_start, eoi_start)
    if scan_start < 0 or eoi_start < scan_start or comment_start < scan_start:
        raise RuntimeError("source JPEG is missing its post-scan COM and terminal EOI")
    if source[comment_start + 2 : comment_start + 4] != b"\xff\xff":
        raise RuntimeError("source JPEG no longer has the pinned oversized COM length")

    encoded = bytearray(source)
    encoded[comment_start : comment_start + 2] = APP1_MARKER
    output = bytes(encoded)
    output_sha256 = sha256(output)
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )
    return output


def verify_pillow_reference(encoded: bytes) -> None:
    """Confirm pinned Pillow opens and decodes the same RGB pixels as the source."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(encoded)) as image:
        image.verify()
    with Image.open(BytesIO(encoded)) as image:
        image.load()
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (8, 8):
            raise RuntimeError(
                "Pillow returned an unexpected JPEG result: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        pixels = image.tobytes()

    pixel_sha256 = sha256(pixels)
    if pixel_sha256 != EXPECTED_PILLOW_RGB_SHA256:
        raise RuntimeError(
            f"Pillow RGB SHA-256 mismatch: expected {EXPECTED_PILLOW_RGB_SHA256}, "
            f"found {pixel_sha256}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    verify_pillow_reference(encoded)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
