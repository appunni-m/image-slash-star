#!/usr/bin/env python3
"""Remove the restart interval from a Pillow restart-coded multi-scan JPEG."""

from __future__ import annotations

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/fixtures/input/images/jpeg/baseline_444_multiscan_interleaved_restart.jpg"
OUTPUT = (
    ROOT
    / "tests/fixtures/input/images/jpeg/baseline_444_multiscan_restart_markers_without_dri.jpg"
)
EXPECTED_SOURCE_SHA256 = "ddbcf29eb1549aae0356661ff2b879b7b2b23b7aae924adbb424af22246e20d7"
EXPECTED_OUTPUT_SHA256 = "c572d8f9a782b421cfddc308da68b3b26f3a371b452cf17cfddfa4a04b16f384"
EXPECTED_PILLOW_RGB_SHA256 = "9c9c6d4e882530085737f66092c48c94e3c3fb21e2a4eca30772a9b07f721190"
DRI_INTERVAL_ONE = bytes.fromhex("ffdd00040001")
SOS_MARKER = b"\xff\xda"


def generate_fixture() -> bytes:
    """Remove only the source DRI segment and verify Pillow's decoded pixels."""
    source = SOURCE.read_bytes()
    source_sha256 = sha256(source).hexdigest()
    if source_sha256 != EXPECTED_SOURCE_SHA256:
        raise RuntimeError(
            f"source JPEG SHA-256 mismatch: expected {EXPECTED_SOURCE_SHA256}, "
            f"found {source_sha256}"
        )

    scan_positions = []
    scan_position = 0
    while (scan_position := source.find(SOS_MARKER, scan_position)) >= 0:
        scan_positions.append(scan_position)
        scan_position += len(SOS_MARKER)

    scan_start = scan_positions[0] if scan_positions else -1
    dri_start = source.find(DRI_INTERVAL_ONE)
    if (
        len(scan_positions) != 2
        or dri_start < 2
        or dri_start >= scan_start
        or source.find(DRI_INTERVAL_ONE, dri_start + len(DRI_INTERVAL_ONE)) >= 0
    ):
        raise RuntimeError("source must contain two scans and one DRI=1 before its first scan")

    candidate = source[:dri_start] + source[dri_start + len(DRI_INTERVAL_ONE) :]
    if candidate.count(SOS_MARKER) != 2 or DRI_INTERVAL_ONE in candidate:
        raise RuntimeError("removing DRI changed the scan count or retained the DRI segment")

    output_sha256 = sha256(candidate).hexdigest()
    if output_sha256 != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(
            f"generated JPEG SHA-256 mismatch: expected {EXPECTED_OUTPUT_SHA256}, "
            f"found {output_sha256}"
        )

    pixel_sha256 = sha256(pillow_rgb(candidate)).hexdigest()
    if pixel_sha256 != EXPECTED_PILLOW_RGB_SHA256:
        raise RuntimeError(
            f"Pillow RGB SHA-256 mismatch: expected {EXPECTED_PILLOW_RGB_SHA256}, "
            f"found {pixel_sha256}"
        )
    return candidate


def pillow_rgb(data: bytes) -> bytes:
    """Verify the candidate with Pillow 12.2.0 and return its RGB pixels."""
    import PIL
    from PIL import Image

    if PIL.__version__ != "12.2.0":
        raise RuntimeError(f"Pillow 12.2.0 is required, found {PIL.__version__}")

    with Image.open(BytesIO(data)) as image:
        image.verify()
    with Image.open(BytesIO(data)) as image:
        image.load()
        if image.format != "JPEG" or image.mode != "RGB" or image.size != (16, 8):
            raise RuntimeError(
                "Pillow returned unexpected candidate metadata: "
                f"format={image.format!r}, mode={image.mode!r}, size={image.size!r}"
            )
        return image.tobytes()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture without rewriting it",
    )
    args = parser.parse_args()

    encoded = generate_fixture()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise RuntimeError(f"{OUTPUT.relative_to(ROOT)} differs from generated bytes")
        print(f"Fixture matches: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    if OUTPUT.exists() and OUTPUT.read_bytes() != encoded:
        raise RuntimeError(f"refusing to replace different existing fixture: {OUTPUT}")
    OUTPUT.write_bytes(encoded)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
